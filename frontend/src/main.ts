async function connect() {
  if (busy) return;
  busy = true;
  controls();
  try {
    await disconnect();
    cars = [];
    total = lastTotal = 0;
    allPaused = false;
    selected = 0;
    const config = await fetch("/api/config").then((r) => {
      if (!r.ok) throw Error("Backend unavailable");
      return r.json();
    });
    client = new FastClient({
      url: mode === "webtransport" ? config.url : config.websocketUrl,
      transport: mode,
      serverCertificateHashes: [
        {
          algorithm: "sha-256",
          value: Uint8Array.from(atob(config.pin), (c) => c.charCodeAt(0)),
        },
      ],
    });
    const active = client;
    client.onStateChange((s) => {
      if (active === client && (s === "failed" || s === "closed")) {
        connected = false;
        controls();
        notice("Connection closed. Reconnect to start a fresh session.");
      }
    });
    await client.connect();
    const n = Number($<HTMLSelectElement>("#size").value);
    for (let id = 0; id < n; id++) {
      const stream = await client.openStream("car-" + id);
      const c: Car = {
        id,
        stream,
        streamId: -1,
        received: 0,
        paused: false,
        slow: false,
        trail: [],
      };
      cars.push(c);
      stream.onFrame((f) => {
        if (f.messageType !== 0x1002) return;
        const s = JSON.parse(decoder.decode(f.payload)) as Sample;
        if (
          s.carId !== id ||
          !Number.isFinite(s.x) ||
          !Number.isFinite(s.y) ||
          s.queued > 32
        )
          return;
        if (capture) {
          const now = performance.now();
          const age = Date.now() - s.generatedAtMs;
          if (Number.isFinite(age) && age >= 0) {
            if (
              capture.seen++ % capture.sampleEvery === 0 &&
              capture.ages.length < 200000
            )
              capture.ages.push(age);
            if (id === 0 && capture.carZeroAges.length < 20000)
              capture.carZeroAges.push(age);
          } else capture.invalidAges++;
          capture.bytes += 12 + f.payload.byteLength;
          capture.counts[id]++;
          capture.maxQueues[id] = Math.max(capture.maxQueues[id], s.queued);
          capture.maxGaps[id] = Math.max(
            capture.maxGaps[id],
            now - capture.lastReceived[id],
          );
          capture.lastReceived[id] = now;
        }
        c.sample = s;
        c.received++;
        total++;
        c.trail.push([s.x, s.y]);
        if (c.trail.length > 80) c.trail.shift();
      });
      await control(c, true);
    }
    connected = true;
    list();
    notice(
      `${n} ${mode === "webtransport" ? "native QUIC streams" : "logical channels on one encrypted WebSocket"} connected. Select a car to inspect its queue or slow its delivery.`,
    );
  } catch (e) {
    await disconnect();
    notice(
      "Unable to connect: " +
        String(e) +
        (mode === "webtransport"
          ? ". Use a Chromium browser with WebTransport support."
          : ". The local TLS certificate must be trusted by this browser; see the README comparison setup."),
    );
  } finally {
    busy = false;
    controls();
  }
}
