async function control(c: Car, initial = false) {
  const ack = await c.stream.sendAndReceive({
    channelId: 512,
    messageType: initial ? 0x1000 : 0x1001,
    requestId: request++,
    payload: encoder.encode(JSON.stringify(settings(c))),
  });
  const data = JSON.parse(decoder.decode(ack.payload));
  c.streamId = data.streamId;
  if (c.paused && c.sample) c.sample.queued = 0;
}
